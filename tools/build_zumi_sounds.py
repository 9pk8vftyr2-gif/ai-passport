#!/usr/bin/env python3
"""Compile website Energy Link sine/envelope parameters to shared 16 kHz PCM.
No downloads, audio services or external libraries. See design notes for source.
"""
import math
import json
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
SPEC = json.loads((ROOT / 'assets/music/zumi-link-tones.json').read_text())
RATE = SPEC['sample_rate']

def tone(frequency, duration, t):
    if t < 0 or t >= duration + SPEC['tail_seconds']:
        return 0
    if t < SPEC['attack_seconds']:
        gain = SPEC['gain_floor'] * ((SPEC['gain_peak'] / SPEC['gain_floor']) ** (t / SPEC['attack_seconds']))
    elif t < duration:
        gain = SPEC['gain_peak'] * ((SPEC['gain_floor'] / SPEC['gain_peak']) ** ((t - SPEC['attack_seconds']) / (duration - SPEC['attack_seconds'])))
    else:
        gain = SPEC['gain_floor']
    return math.sin(2 * math.pi * frequency * t) * gain

parts = ['/* Generated by tools/build_zumi_sounds.py; shared website-tone PCM. */', '#include <stdint.h>']
for name, clip in SPEC['clips'].items():
    frames, notes = clip['frames'], clip['notes']
    pcm = [round(32767 * sum(tone(hz, duration, i / RATE - delay) for hz, duration, delay in notes)) for i in range(frames)]
    parts.append(f'const int16_t z_tone_{name}[{frames}] = {{')
    parts.extend(','.join(str(n) for n in pcm[i:i+20]) + ',' for i in range(0,frames,20))
    parts.append('};')
output = '\n'.join(parts)+'\n'
target = ROOT / 'main/zumi/sounds.c'
if '--check' in sys.argv:
    if target.read_text() != output:
        raise SystemExit('Sound PCM is stale; run tools/build_zumi_sounds.py')
else:
    target.write_text(output)
